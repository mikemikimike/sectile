function page(component) {
  const name = title(component.id);
  const sections = documentedSections(component);
  const cascadeListDetails = cascadeListDetailsSection(component);
  const toastDetails = toastDetailsSection(component);
  assert.ok(sections.usage.length > 0, `${component.id}: requires at least one Usage scenario`);
  const usage = scenarioSection(component, sections.usage);
  const examples = optionalExamplesSection(component, sections.examples, sections.usage.length);
  const outsideInteraction = outsideInteractionSection(component);
  const drawerGesture = drawerGestureSection(component);
  const positioning = positioningSection(component);
  const usageBody = [usage, cascadeListDetails, toastDetails].filter(Boolean).join('\n\n');
  return `<!-- Generated by scripts/generate-component-pages.mjs. -->
# ${name}

${description(component)}

## Usage

${usageBody}${examples}${outsideInteraction}${drawerGesture}${positioning}${motionExampleSection(component)}${applicationExampleSection(component)}

${componentReferenceLink(component)}

${accessibilitySection(component)}
`;
}

